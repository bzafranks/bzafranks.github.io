/* =====================================================================
   Build script for /public-sector-ai/
   ---------------------------------------------------------------------
   Reads content.mjs and writes static HTML that GitHub Pages serves
   as-is (no build step on GitHub):

     public-sector-ai/index.html
     public-sector-ai/case-studies.html
     public-sector-ai/learning-module.html
     public-sector-ai/sources.html
     public-sector-ai/_src/pdf/print.html      (PDF source, not published)

   Usage (from the repo root):
     node public-sector-ai/_src/build.mjs            HTML only, no dependencies
     node public-sector-ai/_src/build.mjs --pdf      HTML + PDF (needs Playwright)
     node public-sector-ai/_src/build.mjs --strict   fail if any PENDING claim remains

   Folders starting with "_" are not published by GitHub Pages (Jekyll),
   so _src/ stays private to the repo.
   ===================================================================== */
