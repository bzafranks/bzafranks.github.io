/* ---------- reusable blocks ---------- */
const factsHtml = (facts) => facts.map((f) => `<div class="x-fact"><span class="num">${esc(f.num)}${pend(f.src, f.label)}</span><span class="lbl">${esc(f.label)}</span></div>`).join("");

function diagramHtml(d) {
  let inner = "";
  if (d.kind === "flow") inner = `<ol class="x-flow">${li(d.steps)}</ol>`;
  if (d.kind === "cycle") inner = `<ol class="x-cycle">${li(d.steps)}</ol><p class="x-cycle-ret" aria-hidden="true">↺ repeat the cycle</p>`;
  if (d.kind === "hub") inner = `<div class="x-hub"><div class="c">${esc(d.center)}</div><ul>${li(d.steps)}</ul></div>`;
  return `<figure class="x-diagram" aria-label="${esc(d.caption)}">${inner}<figcaption>${ev("D")} ${esc(d.caption)}</figcaption></figure>`;
}

function frameworkHtml() {
  const f = C.framework;
  const lv = f.levels.map((l, i) => `
          <li style="--i:${i}">
            <span class="lv">Level ${l.n} · <span>${esc(l.focus)}</span></span>
            <h3>${esc(l.name)}</h3>
            <ul>${li(l.items)}</ul>
            <p class="out"><strong>Outcome:</strong> ${esc(l.outcome)}</p>
          </li>`).join("");
  return `<div class="x-fw" role="group" aria-label="${esc(f.name)}: five ascending levels">
        <ol>${lv}
        </ol>
        <div class="x-fw-base"><strong>Across every level</strong>${f.crossCutting.map((c) => `<span>${esc(c)}</span>`).join("")}</div>
        <p class="x-fw-axis" aria-hidden="true"><span>Individual awareness</span><span>→ increasing capability and organizational impact →</span><span>Sustained performance</span></p>
      </div>`;
}

