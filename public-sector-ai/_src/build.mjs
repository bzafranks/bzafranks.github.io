const pendingCount = { n: 0, items: [] };
const pend = (src, what) => {
  if (src !== C.PENDING) return "";
  pendingCount.n++; pendingCount.items.push(what);
  return `<span class="x-pending" title="${esc(C.PENDING)}">to verify</span>`;
};
const li = (arr) => arr.map((x) => `<li>${esc(x)}</li>`).join("");
