#!/usr/bin/env node
/* =====================================================================
   Build script for /curriculum-portfolio/
   ---------------------------------------------------------------------
   Each page is an HTML fragment in _src/pages/. The first line is a
   comment holding JSON metadata:  <!--meta {"title": "...", "desc": "..."} -->
   This script wraps every fragment in the shared shell (header, crumb,
   footer, disclosure, Listen reader) and writes it to /curriculum-portfolio/.

   Tokens available inside fragments:
     {{DISCLOSURE}}            the required independence disclosure
     {{LABEL:rep|sim|ai|ill}}  an evidence label chip
     {{CARDS:ws1,ws2}}         work-sample cards from samples.mjs
     {{PATHWAYS}}              the five pathway buttons
     {{NEXT:ws2}}              "next sample" link

   Usage (from the repo root):
     node curriculum-portfolio/_src/build.mjs          HTML only
     node curriculum-portfolio/_src/build.mjs --pdf    HTML + PDFs (needs Playwright, python3 + pypdf)

   Folders starting with "_" are not published by GitHub Pages.
   ===================================================================== */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { SAMPLES, LABELS, PATHWAYS } from "./samples.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "..");
const PAGES = join(HERE, "pages");
const PARTIALS = join(HERE, "partials");
const args = new Set(process.argv.slice(2));
const BASE = "https://bzafranks.github.io/curriculum-portfolio/";
const NAME = "Dr. Barbara Zá Franks, EdD";
const EMAIL = "barbara.franks@mydreamedu.org";
const VERSION = "Version 1.0 · November 2026";

const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export const DISCLOSURE = "These materials are independently developed curriculum demonstration samples created for professional portfolio purposes. They are not affiliated with, endorsed by, or commissioned by any previous or prospective employer.";

const label = (k) => `<span class="c-label ${k}">${esc(LABELS[k])}</span>`;
const card = (id) => {
  const s = SAMPLES[id];
  return `<a class="c-card" href="${s.file}"><span class="n">${s.n} ${label(s.label)}</span><h3>${esc(s.title)}</h3><p><em>${esc(s.hook)}</em></p><p>${esc(s.card)}</p><span class="tags">${s.tags.map(esc).join(" · ")}</span><span class="more">Open ${s.n} →</span></a>`;
};
const pathways = () => `<nav class="c-path" aria-label="Pathways by role">${PATHWAYS.map((p) => `<a href="${p.file}"><strong>${esc(p.name)}</strong><span>${esc(p.for)}</span></a>`).join("")}</nav>`;

function expand(html) {
  return html
    .replace(/\{\{INCLUDE:([\w-]+)\}\}/g, (_, n) => readFileSync(join(PARTIALS, n + ".html"), "utf8"))
    .replace(/\{\{DISCLOSURE\}\}/g, `<p class="c-disclosure"><strong>Disclosure.</strong> ${esc(DISCLOSURE)}</p>`)
    .replace(/\{\{LABEL:(\w+)\}\}/g, (_, k) => label(k))
    .replace(/\{\{CARDS:([\w,]+)\}\}/g, (_, ids) => `<div class="c-cards">${ids.split(",").map(card).join("")}</div>`)
    .replace(/\{\{PATHWAYS\}\}/g, pathways())
    .replace(/\{\{NEXT:(\w+)\}\}/g, (_, id) => `<p class="no-print"><a class="btn ghost" href="${SAMPLES[id].file}">Next: ${SAMPLES[id].n}, ${esc(SAMPLES[id].title)} →</a></p>`);
}

const NAV = [
  ["index.html", "Overview"],
  ["how-i-design.html", "How I design"],
  ["work-samples.html", "Work samples"],
  ["alignment.html", "Alignment"],
  ["references.html", "References"],
  ["downloads.html", "Downloads"],
];

function layout(file, meta, body) {
  const navHtml = NAV.map(([h, t]) => `<li><a href="${h}"${h === file || (meta.nav === h) ? ' aria-current="page"' : ""}>${t}</a></li>`).join("");
  const canonical = BASE + (file === "index.html" ? "" : file);
  const title = meta.title + (file === "index.html" ? "" : ` · ${NAME}`);
  return `<!DOCTYPE html>
<!-- GENERATED by curriculum-portfolio/_src/build.mjs from _src/pages/${file}. Edit the fragment, not this page. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(meta.desc)}">
  <meta name="author" content="${esc(NAME)}">
  <link rel="canonical" href="${canonical}">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(meta.desc)}">
  <meta property="og:url" content="${canonical}">
  <meta property="og:image" content="https://bzafranks.github.io/assets/img/barbara-franks.jpg">
  <meta name="twitter:card" content="summary">
  <meta name="theme-color" content="#1f3a5f">
  <link rel="stylesheet" href="../assets/css/design-system.css">
  <link rel="stylesheet" href="cp.css">
</head>
<body class="cp">
  <a class="skip-link" href="#main">Skip to main content</a>
  <div class="c-crumb"><div class="container">
    <a href="../index.html">← Main portfolio: bzafranks.github.io</a>
    <a href="downloads.html">Download PDFs</a>
  </div></div>
  <header class="site-header">
    <nav class="nav" aria-label="Curriculum portfolio">
      <a class="brand" href="index.html">
        <span class="logo" aria-hidden="true">BF</span>
        <span class="brand-text"><span class="brand-title">${esc(NAME)}</span><span class="brand-sub">Curriculum Development · Instructional Design · Editorial QA</span></span>
      </a>
      <button class="nav-toggle" aria-label="Toggle menu" aria-expanded="false">☰</button>
      <ul class="nav-links">${navHtml}</ul>
    </nav>
  </header>
  <main id="main">
${expand(body)}
  </main>
  <footer class="site-footer">
    <div class="container">
      <div class="footer-grid">
        <div>
          <h4>${esc(NAME)}</h4>
          <p style="color:#c9d6e6;">Curriculum development, instructional design and editorial quality assurance.</p>
        </div>
        <div>
          <h4>This section</h4>
          <ul>
            <li><a href="index.html">Overview</a></li>
            <li><a href="work-samples.html">All work samples</a></li>
            <li><a href="how-i-design.html">How I design</a></li>
            <li><a href="references.html">References and rights</a></li>
            <li><a href="downloads.html">Downloads</a></li>
          </ul>
        </div>
        <div>
          <h4>Connect</h4>
          <ul>
            <li><a href="mailto:${EMAIL}">${EMAIL}</a></li>
            <li><a href="https://www.linkedin.com/in/barbara-franks/" target="_blank" rel="noopener">LinkedIn</a></li>
            <li><a href="../resume.html">Résumé</a></li>
            <li><a href="../index.html">Main portfolio</a></li>
          </ul>
        </div>
      </div>
      <p class="c-foot-note">${esc(DISCLOSURE)} All texts, items and characters are original. No proprietary curriculum, internal assessment items, confidential employer information or student data appear in this section.</p>
      <div class="footer-bottom">${VERSION} · © ${esc(NAME)}</div>
    </div>
  </footer>
  <script src="../assets/js/portfolio.js"></script>${meta.script ? `\n  <script src="${meta.script}"></script>` : ""}
</body>
</html>
`;
}

/* ---------- build HTML ---------- */
const files = readdirSync(PAGES).filter((f) => f.endsWith(".html")).sort();
const built = [];
for (const f of files) {
  const raw = readFileSync(join(PAGES, f), "utf8");
  const m = raw.match(/^<!--meta\s+(\{[\s\S]*?\})\s*-->\s*\n/);
  if (!m) throw new Error(`${f}: missing <!--meta {...} --> first line`);
  const meta = JSON.parse(m[1]);
  const body = raw.slice(m[0].length);
  writeFileSync(join(OUT, f), layout(f, meta, body));
  built.push({ f, meta });
}
console.log(`Built ${built.length} pages.`);

/* ---------- PDFs ---------- */
if (args.has("--pdf")) {
  const require = createRequire(import.meta.url);
  let chromium;
  try { ({ chromium } = require("playwright")); } catch { ({ chromium } = createRequire("/opt/node22/lib/node_modules/")("playwright")); }
  const DL = join(OUT, "downloads");
  mkdirSync(DL, { recursive: true });
  const TMP = join(HERE, "pdf");
  mkdirSync(TMP, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const pdfOf = async (f, out) => {
    await page.goto(pathToFileURL(join(OUT, f)).href, { waitUntil: "load" });
    await page.evaluate(() => { document.querySelectorAll("details").forEach((d) => (d.open = true)); document.querySelectorAll("[data-print-show]").forEach((e) => (e.hidden = false)); });
    await page.emulateMedia({ media: "print" });
    await page.pdf({ path: out, format: "Letter", printBackground: true, margin: { top: "0.6in", bottom: "0.7in", left: "0.6in", right: "0.6in" },
      displayHeaderFooter: true, headerTemplate: "<span></span>",
      footerTemplate: `<div style="font-size:8px;width:100%;padding:0 0.6in;color:#555;display:flex;justify-content:space-between;font-family:Segoe UI,Arial,sans-serif"><span>${esc(NAME)} · Independent demonstration sample</span><span><span class="pageNumber"></span> / <span class="totalPages"></span></span></div>` });
  };
  const singles = {};
  for (const { f, meta } of built) {
    if (!meta.pdf) continue;
    const out = join(DL, meta.pdf);
    await pdfOf(f, out);
    singles[f] = out;
    console.log("PDF", meta.pdf);
  }
  await browser.close();
  // Packets: merged selections, defined in packets.json
  const packets = JSON.parse(readFileSync(join(HERE, "packets.json"), "utf8"));
  for (const p of packets) {
    const parts = p.pages.map((f) => singles[f] || join(DL, f)).filter((x) => existsSync(x));
    execFileSync("python3", ["-I", join(HERE, "merge_pdf.py"), join(DL, p.out), ...parts]);
    console.log("Packet", p.out, `(${parts.length} parts)`);
  }
}
